import { useCallback, useEffect, useRef, useState } from 'react';
import { getExamAiOverview, generateExamAiOverview } from '../services/mockExamResultService';

// How often an overview being generated (by anyone) checks whether it is ready
const GENERATING_POLL_MS = 4000;

const NOTHING = { examId: null, loading: false, error: '', data: null };

/**
 * The AI overview of the open exam on Exam Results (pages/shared/AiOverviewView.jsx). It loads
 * the first time `enabled` is true for an exam (the AI Overview view is open) and keeps it while
 * the exam stays open. While one is being generated, here or by someone else, it checks every
 * few seconds until it is ready.
 *
 * Returns { loading, error, data, isGenerating, generateError, selectedVersion, selectVersion,
 * generate, reload }. data is the server's answer: { limit, used, remaining, generating,
 * versions, overview }. generate() resolves to { ok, data | error }.
 */
export default function useExamAiOverview(examId, enabled) {
  const [state, setState] = useState(NOTHING);
  // null shows the latest version
  const [selectedVersion, setSelectedVersion] = useState(null);
  // The exam whose generate request is waiting for its answer
  const [requestingId, setRequestingId] = useState(null);
  const [generateError, setGenerateError] = useState(null);

  // Answers for an exam that is no longer open are dropped
  const openExamId = useRef(examId);
  useEffect(() => {
    openExamId.current = examId;
    setSelectedVersion(null);
    setGenerateError(null);
  }, [examId]);

  const load = useCallback(async (id, version = null, { quiet = false } = {}) => {
    if (!quiet) {
      setState((prev) => ({ examId: id, loading: true, error: '', data: prev.examId === id ? prev.data : null }));
    }
    try {
      const data = await getExamAiOverview(id, version);
      if (openExamId.current === id) setState({ examId: id, loading: false, error: '', data });
    } catch (err) {
      if (openExamId.current !== id) return;
      // A version that is gone shows the latest instead
      if (err.status === 404 && version !== null) {
        setSelectedVersion(null);
        load(id, null, { quiet });
        return;
      }
      setState((prev) => ({
        examId: id,
        loading: false,
        // A check made in the background keeps what is shown
        error: quiet ? prev.error : (err.message || 'The AI overview could not be loaded.'),
        data: prev.examId === id ? prev.data : null,
      }));
    }
  }, []);

  const isCurrent = state.examId === examId;

  useEffect(() => {
    if (enabled && examId && !isCurrent) load(examId);
  }, [enabled, examId, isCurrent, load]);

  // One being generated by someone else (or by this page before a reload) is checked on until ready
  const generatingElsewhere = isCurrent && Boolean(state.data?.generating) && requestingId !== examId;
  useEffect(() => {
    if (!generatingElsewhere) return undefined;
    const timer = setInterval(() => load(examId, selectedVersion, { quiet: true }), GENERATING_POLL_MS);
    return () => clearInterval(timer);
  }, [generatingElsewhere, examId, selectedVersion, load]);

  const selectVersion = useCallback((version) => {
    const next = version || null;
    setSelectedVersion(next);
    load(examId, next);
  }, [examId, load]);

  const generate = useCallback(async () => {
    const id = examId;
    setRequestingId(id);
    setGenerateError(null);
    try {
      const data = await generateExamAiOverview(id);
      if (openExamId.current === id) {
        setSelectedVersion(null);
        setState({ examId: id, loading: false, error: '', data });
      }
      return { ok: true, data };
    } catch (err) {
      if (openExamId.current === id) {
        const code = err.data?.code || null;
        // Someone else is generating one, or the last generation was just used: show where it stands
        if (err.status === 409) load(id, selectedVersion, { quiet: true });
        if (code !== 'generating') {
          setGenerateError({ code, message: err.data?.message || err.message || 'The overview could not be written.' });
        }
      }
      return { ok: false, error: err };
    } finally {
      setRequestingId((prev) => (prev === id ? null : prev));
    }
  }, [examId, selectedVersion, load]);

  const reload = useCallback(() => load(examId, selectedVersion), [examId, selectedVersion, load]);

  return {
    loading: isCurrent ? state.loading : Boolean(enabled && examId),
    error: isCurrent ? state.error : '',
    data: isCurrent ? state.data : null,
    isGenerating: requestingId === examId || Boolean(isCurrent && state.data?.generating),
    generateError,
    selectedVersion,
    selectVersion,
    generate,
    reload,
  };
}
